const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const {_electron} = require('playwright');

(async () => {
  const root = path.resolve(__dirname, '..');
  const dir = await fs.mkdtemp(path.join(os.tmpdir(), 'markdownre-outline-'));
  const file = path.join(dir, 'headings.md');
  const body = Array.from({length:15},(_,i)=>`Paragraph ${i+1}: ${'long text '.repeat(16)}\n`).join('\n');
  await fs.writeFile(file, `# First heading\n\n${body}\n## Repeated\n\n${body}\n### Third *emphasis*\n\n${body}\n#### Fourth\n\n${body}\n##### Fifth\n\n${body}\n###### Sixth\n\n${body}\n## Repeated\n\n${body}\n\`\`\`md\n# Not a heading\n\`\`\`\n\n## Last tiny\n`);
  const app = await _electron.launch({executablePath:process.env.ELECTRON_TEST_BINARY || require('electron'), args:[...(process.env.ELECTRON_TEST_PACKAGED?[]:[root]),`--user-data-dir=${path.join(dir,'profile')}`,file,...(process.env.ELECTRON_TEST_CONTAINER?['--no-sandbox','--disable-gpu']:[])]});
  try {
    const page = await app.firstWindow();
    const toggle = page.locator('#outline-toggle'), panel=page.locator('#outline-panel'), entries=page.locator('.outline-entry');
    await page.waitForFunction(()=>document.querySelectorAll('#preview h1, #preview h2, #preview h3, #preview h4, #preview h5, #preview h6').length===8);
    assert.equal(await panel.isHidden(),true);
    assert.equal(await toggle.getAttribute('aria-expanded'),'false');
    const location = await page.evaluate(() => {
      const button = document.querySelector('#outline-toggle').getBoundingClientRect();
      const pane = document.querySelector('#preview-pane').getBoundingClientRect();
      return {x:button.left-pane.left,y:button.top-pane.top,inToolbar:!!document.querySelector('#toolbar #outline-toggle')};
    });
    assert(location.x>=0 && location.x<=8 && location.y>=0 && location.y<=8 && !location.inToolbar);
    await toggle.click();
    assert.equal(await panel.isVisible(),true);
    assert.equal(await toggle.getAttribute('aria-expanded'),'true');
    const handle=page.locator('#outline-splitter');
    const drag=async distance=>{const box=await handle.boundingBox();await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.down();await page.mouse.move(box.x+box.width/2+distance,box.y+box.height/2,{steps:5});await page.mouse.up();};
    const width=()=>panel.evaluate(element=>element.getBoundingClientRect().width);
    const initialWidth=await width();
    await drag(100);
    assert((await width())>initialWidth+80,'dragging right widens the outline');
    await drag(-1000);
    assert(Math.abs((await width())-160)<2,'dragging left respects minimum width');
    await drag(2000);
    assert(Math.abs((await width())-480)<2,'dragging right respects maximum width');
    await handle.focus();await page.keyboard.press('ArrowLeft');
    assert(Math.abs((await width())-464)<2,'keyboard adjusts the outline width');
    await drag(-224);
    assert.deepEqual(await entries.allTextContents(),['First heading','Repeated','Third emphasis','Fourth','Fifth','Sixth','Repeated','Last tiny']);
    const depths=await entries.evaluateAll(items=>items.map(item=>item.style.getPropertyValue('--depth')));
    assert.deepEqual(depths,['0','1','2','3','4','5','1','1']);
    await entries.nth(1).click();
    const firstPosition=await page.locator('#preview').evaluate(e=>e.scrollTop);
    await entries.nth(6).click();
    const lastPosition=await page.locator('#preview').evaluate(e=>e.scrollTop);
    assert(lastPosition>firstPosition+100,`duplicate headings should jump to their distinct positions: ${firstPosition}, ${lastPosition}`);
    await page.waitForFunction(()=>document.querySelectorAll('.outline-entry[aria-current="true"]').length===1);
    await entries.last().click();
    await page.waitForFunction(()=>document.querySelector('.outline-entry:last-child')?.getAttribute('aria-current')==='true');
    if (process.env.MARKDOWNRE_OUTLINE_SCREENSHOT) await page.screenshot({path:process.env.MARKDOWNRE_OUTLINE_SCREENSHOT});
    const printHtml = await page.evaluate(()=>window.preparePDFExport());
    assert(!printHtml.includes('outline-panel')&&!printHtml.includes('outline-entry'),'outline must not be printed');
    await page.locator('[data-layout="horizontal"]').click();
    await drag(2000);
    const splitSizes = await page.evaluate(() => ({panel:document.querySelector('#outline-panel').getBoundingClientRect().width,pane:document.querySelector('#preview-pane').clientWidth,preview:document.querySelector('#preview').clientWidth}));
    assert(splitSizes.panel <= splitSizes.pane * 0.6 + 1 && splitSizes.preview > splitSizes.pane * 0.35,'narrow split view retains space for the preview');
    await page.locator('.monaco-editor').click({position:{x:100,y:30}});
    await page.keyboard.press(process.platform==='darwin'?'Meta+Home':'Control+Home');
    await page.waitForFunction(()=>document.querySelector('#preview').scrollTop < 5);
    await page.locator('.monaco-editor').hover();
    await page.mouse.wheel(0, 30000);
    await page.waitForFunction(()=>document.querySelector('#preview').scrollTop > 50);
    assert.equal(await panel.isVisible(),true);
    await page.locator('#outline-close').click();
    assert.equal(await panel.isHidden(),true);
    assert.equal(await handle.isHidden(),true);
    await toggle.click();
    assert(Math.abs((await width())-splitSizes.panel)<2,'reopening keeps the selected width');
    await page.locator('[data-layout="editor"]').click();
    assert.equal(await toggle.isDisabled(),true);
    assert.equal(await panel.isHidden(),true);
    await page.locator('.monaco-editor').click({position:{x:100,y:30}});
    await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
    await page.keyboard.insertText('# Changed\n\n## Child\n\nPlain text');
    await page.locator('[data-layout="horizontal"]').click();
    await page.waitForFunction(()=>document.querySelectorAll('.outline-entry').length===2 && document.querySelector('.outline-entry').textContent==='Changed');
    assert.equal(await panel.isVisible(),true);
    assert.deepEqual(await entries.allTextContents(),['Changed','Child']);
    await page.locator('[data-layout="vertical"]').click();
    assert.equal(await panel.isVisible(),true);
    await page.locator('[data-layout="editor"]').click();
    await page.locator('.monaco-editor').click({position:{x:100,y:30}});
    await page.keyboard.press(process.platform==='darwin'?'Meta+A':'Control+A');
    await page.keyboard.insertText('Plain text only');
    await page.locator('[data-layout="preview"]').click();
    await page.waitForFunction(()=>!document.querySelector('#outline-empty').hidden);
    assert.equal(await entries.count(),0);
    assert.equal(await panel.isVisible(),true);
    await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:2});});
    console.log('PASS: outline levels, duplicate navigation, modes, updates, empty state and PDF isolation');
  } finally { await app.evaluate(({dialog})=>{dialog.showMessageBox=async()=>({response:2});}).catch(()=>{});await app.close();await fs.rm(dir,{recursive:true,force:true}); }
})().catch(error=>{console.error(error);process.exitCode=1;});
